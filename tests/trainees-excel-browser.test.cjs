const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {spawn}=require('node:child_process');
(async()=>{
  const server=spawn(process.execPath,[path.join(__dirname,'../tools/design-preview.cjs')],{stdio:['ignore','pipe','inherit'],env:{...process.env,IBTA_PREVIEW_PORT:'4176'}});
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);});
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  try{
    const page=await browser.newPage({viewport:{width:1500,height:1000}}),errors=[];
    require('./sheet-toolbar-helper.cjs')(page);
    page.on('pageerror',e=>errors.push(e.message));await page.goto('http://127.0.0.1:4176/');await page.locator('#trainees-tab').click();
    await page.waitForFunction(()=>document.getElementById('sheet-status').textContent==='تم الحفظ');
    const editCell=page.locator('td[data-v="0"][data-col="2"]');
    await editCell.dblclick();await page.keyboard.press('Control+a');await page.keyboard.insertText('اختبار الحفظ التلقائي');
    await page.waitForFunction(()=>document.getElementById('sheet-status').textContent==='تم الحفظ');
    assert.equal(await editCell.textContent(),'اختبار الحفظ التلقائي');
    assert.equal(await editCell.getAttribute('contenteditable'),'true','Saving does not end typing or reset the caret');
    await page.locator('#sheet-reload').click();await page.waitForFunction(()=>document.getElementById('sheet-status').textContent==='تم الحفظ');
    assert.equal(await editCell.textContent(),'اختبار الحفظ التلقائي','Autosave persists before leaving the edited cell');
    assert.equal(await page.locator('#sheet-add-1000').count(),0);
    await page.locator('#sheet-add-bulk-btn').click();
    await page.locator('#sheet-freeze').click();assert.equal(await page.locator('#sheet-grid').evaluate(el=>el.classList.contains('sheet-freeze-column')),true);
    await page.locator('#sheet-address').fill('D150');await page.locator('#sheet-address').press('Enter');
    assert.equal(await page.locator('td.sheet-current').getAttribute('data-col'),'3');
    assert.equal(await page.locator('td.sheet-current').getAttribute('data-v'),'149');
    assert.equal(await page.locator('#sheet-address').inputValue(),'D150');
    await page.locator('#sheet-address').fill('ZZ999999');await page.locator('#sheet-address').press('Enter');
    assert.equal(await page.locator('#sheet-status').getAttribute('data-error'),'true');
    assert.equal(await page.locator('.sheet-ribbon-tabs [role="tab"]').count(),0);
    assert.equal(await page.locator('.sheet-ribbon-panel').count(),1);
    await page.setViewportSize({width:390,height:844});await page.locator('#sheet-address').fill('A1');await page.locator('#sheet-address').press('Enter');
    assert.equal(await page.locator('#sheet-more-tools').count(),0);assert.equal(await page.locator('#sheet-save').isVisible(),true,'Save remains available');
    assert.equal(await page.locator('#sheet-count').textContent().then(s=>s.includes('إجمالي الصفوف')),true);
    await page.locator('.sheet-report-panel summary').click();
    assert.equal(await page.locator('[data-action="operations"]').isDisabled(),true);
    await page.locator('[data-field="operations"]').fill('https://docs.google.com/spreadsheets/d/example/edit');
    await page.locator('[data-field="bridge"]').fill('https://script.google.com/macros/s/example/exec');
    assert.equal(await page.locator('[data-action="operations"]').isEnabled(),true);
    assert.equal(await page.locator('[data-action="success"]').isDisabled(),true);
    assert.equal(await page.locator('#sheet-address').inputValue(),'A1');
    await page.setViewportSize({width:1500,height:1000});
    await page.evaluate(()=>{const old=previewSheets.get('demo-admin');const cells=Array.from({length:3068},(_,i)=>{const row=Array(13).fill('');row[2]='متدرب '+(i+1);row[3]='Trainee '+(i+1);return row;});previewSheets.set('demo-admin',{...old,cells,format:{...old.format,headers:{499:'Last column'}},version:old.version+1});});
    await page.locator('#sheet-reload').click();await page.waitForFunction(()=>document.getElementById('sheet-status').textContent==='تم الحفظ');
    assert.equal(await page.locator('#sheet-prev,#sheet-next,#sheet-page-size').count(),0,'Pagination controls are removed');
    assert.equal(await page.locator('#sheet-grid').getAttribute('aria-rowcount'),'4069','All 3068 data rows, 1000 empty input rows and the header belong to one continuous grid');
    assert.ok(await page.locator('#sheet-grid tbody th[data-rowv]').count()<100,'Only viewport rows are mounted to keep thousands of records responsive');
    assert.equal(await page.locator('#sheet-grid thead th[data-col]').count(),500);
    assert.ok(await page.locator('#sheet-grid td[data-col]').count()<40000,'3068 rows by 500 columns never create a million DOM cells');
    assert.doesNotMatch(await page.locator('#sheet-count').textContent(),/Page|صفحة/);
    await page.locator('#sheet-address').fill('C3068');await page.locator('#sheet-address').press('Enter');
    assert.equal(await page.locator('td.sheet-current').getAttribute('data-v'),'3067','Last row is reachable without changing pages');
    assert.equal(await page.locator('td[data-v="3067"][data-col="2"]').textContent(),'متدرب 3068');
    await page.keyboard.press('F2');await page.keyboard.press('Control+a');await page.keyboard.insertText('آخر صف');await page.keyboard.press('Enter');
    await page.waitForFunction(()=>!Trainees.hasDraft());assert.equal(await page.evaluate(()=>previewSheets.get('demo-admin').cells[3067][2]),'آخر صف');
    // The old design fixture omits reports and some non-trainee page globals.
    const fixtureErrors=new Set(['codes is not defined',"Cannot read properties of null (reading 'addEventListener')",'TraineeReports is not defined']);
    assert.deepEqual(errors.filter(message=>!fixtureErrors.has(message)),[]);
    console.log('PASS: ribbon controls, continuous 3068-row sheet, last-row navigation/editing, invalid addresses and mobile layout');
  }finally{await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exitCode=1;});
