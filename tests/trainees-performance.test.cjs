const assert=require('node:assert/strict');
const D=require('../trainees-core.js');
const rows=D.normalize(Array.from({length:3068},(_,r)=>Array.from({length:500},(_,c)=>c===2?'Trainee '+r:'')));
const start=performance.now(),edited=D.paste(rows,[['Changed']],1500,2);
const editMs=performance.now()-start;
assert.notEqual(edited,rows);assert.notEqual(edited[1500],rows[1500]);
assert.equal(edited[0],rows[0]);assert.equal(edited[3067],rows[3067],'Unchanged rows share immutable storage');
assert.equal(rows[1500][2],'Trainee 1500','Undo snapshots retain original values');
assert.ok(Object.isFrozen(edited)&&Object.isFrozen(edited[1500]));
assert.equal(D.normalize(edited),edited,'Already validated snapshots are reused for saves');
assert.throws(()=>D.paste(rows,[['x'.repeat(2001)]],100,2),/CELL_LIMIT/);
assert.throws(()=>D.pasteMapped(rows,[[123]],100,[2]),/CELL_LIMIT/);
const saved=D.storage(edited);
assert.equal(saved[0].length,500,'First row preserves all empty custom columns');
assert.equal(saved[1500].length,13);
assert.deepEqual(D.normalize(saved),edited,'Compact persistence reconstructs every cell and column');
assert.ok(JSON.stringify(saved).length<JSON.stringify(edited).length/10,'Empty trailing columns do not inflate save requests');
const last=D.paste(edited,[['00123']],3067,499);
assert.equal(D.storage(last)[3067][499],'00123','Far columns and leading zeros survive saves');
const expanded=D.paste(D.normalize([['A'],['B']]),[['Tail']],1,499);
assert.equal(expanded[0].length,500);assert.equal(expanded[0][0],'A');assert.equal(expanded[1][499],'Tail');
const emptyWide=[D.blank(),D.blank(500)];
assert.equal(D.paste(emptyWide,[['First edit']],0,2)[0].length,500,'Editing an empty wide sheet retains its width');
assert.equal(D.pasteMapped(emptyWide,[['First paste']],0,[2])[0].length,500);
const cleared=D.paste(D.normalize([['A'],['B']]),[['']],1,0);
assert.equal(cleared.length,1,'Clearing final populated row still trims trailing empty rows');
console.log('PASS: immutable edits, shared undo rows, validation and compact 3068 × 500 save roundtrip; single data edit '+editMs.toFixed(1)+' ms');
